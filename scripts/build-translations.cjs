// Run: node scripts/build-translations.cjs
// CSV is the editable source; translations-data.js is generated for file:// support.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ROOT = path.resolve(__dirname, '..');
const LANGUAGES = ['zh-TW', 'en', 'ja', 'ko'];
const HEADERS = ['card_id','language','name','subtitle','ability_1_title','ability_1_text','ability_2_title','ability_2_text'];

// Handles UTF-8 BOM, quoted commas, escaped quotes, CRLF and real cell line breaks.
function parseCSV(input) {
  const text = input.replace(/^\uFEFF/, '');
  const rows = []; let row = [], field = '', quoted = false, closed = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (quoted) {
      if (char === '"') {
        if (text[i+1] === '"') { field += '"'; i++; }
        else { quoted = false; closed = true; }
      } else field += char;
    } else if (char === ',') { row.push(field); field = ''; closed = false; }
    else if (char === '\r' || char === '\n') {
      if (char === '\r' && text[i+1] === '\n') i++;
      row.push(field); if (row.some(value => value !== '')) rows.push(row);
      row = []; field = ''; closed = false;
    } else if (char === '"' && !field && !closed) quoted = true;
    else if (closed || char === '"') throw Error('CSV 引號格式錯誤，請以 CSV UTF-8 格式重新儲存。');
    else field += char;
  }
  if (quoted) throw Error('CSV 有未關閉的引號。');
  if (field || row.length || closed) { row.push(field); rows.push(row); }
  return rows;
}

function compile(text, cards) {
  const [headers, ...rows] = parseCSV(text);
  if (JSON.stringify(headers) !== JSON.stringify(HEADERS)) throw Error('CSV 欄位名稱或順序不符。');
  const byId = new Map(cards.map(card => [card.id, card]));
  const result = {};
  for (const [index, row] of rows.entries()) {
    if (row.length !== HEADERS.length) throw Error(`第 ${index+2} 筆的欄位數不符。`);
    const [rawId, language, name, subtitle, title1, text1, title2, text2] = row;
    const id = rawId.trim().padStart(2, '0');
    if (!byId.has(id) || !LANGUAGES.includes(language)) throw Error(`未知卡牌或語言：${id}/${language}`);
    if (result[id]?.[language]) throw Error(`重複資料：${id}/${language}`);
    const values = byId.get(id).abilities.length === 2 ? [name, subtitle, title1, text1, title2, text2] : [name, subtitle, title1, text1];
    if (values.some(value => !value.trim())) throw Error(`翻譯欄位不完整：${id}/${language}`);
    if (byId.get(id).abilities.length === 1 && (title2 || text2)) throw Error(`技能數量不符：${id}/${language}`);
    const abilities = [{title:title1, text:text1}];
    if (title2) abilities.push({title:title2, text:text2});
    result[id] ||= {};
    result[id][language] = {name, subtitle, abilities};
  }
  for (const card of cards) if (!result[card.id]?.['zh-TW']) throw Error(`缺少中文基準：${card.id}`);
  return result;
}

if (require.main === module) {
  try {
    const context = {window:{}};
    vm.runInNewContext(fs.readFileSync(path.join(ROOT,'cards-data.js'),'utf8'),context);
    const translations = compile(fs.readFileSync(path.join(ROOT,'data/card-translations.csv'),'utf8'),context.window.CARDS);
    const output = '// Generated from data/card-translations.csv. Do not edit this file by hand.\nwindow.CARD_TRANSLATIONS = '+JSON.stringify(translations,null,2)+';\n';
    const target = path.join(ROOT,'translations-data.js');
    fs.writeFileSync(target+'.tmp',output);
    fs.renameSync(target+'.tmp',target);
    const count = Object.values(translations).reduce((sum,languages) => sum+Object.keys(languages).length,0);
    console.log(`已轉換 ${count} 筆翻譯。重新整理網頁即可看到更新。`);
    if (count !== context.window.CARDS.length*4) console.log('部分語言未提供，網站會回退至該張卡的中文版本。');
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = {parseCSV, compile};
