// Generate the initial catalog once from existing assets. INSERT OR IGNORE preserves admin edits.
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const ctx = {window:{}};
for (const file of ['cards-data.js','translations-data.js']) vm.runInNewContext(fs.readFileSync(path.join(root,file),'utf8'),ctx);
const quote = value => "'" + String(value).replaceAll("'", "''") + "'";
const rows = ctx.window.CARDS.map(card => {
  const data = {...card, translations:ctx.window.CARD_TRANSLATIONS[card.id]};
  return `INSERT OR IGNORE INTO catalog_cards(id,data,status) VALUES (${quote(card.id)},${quote(JSON.stringify(data))},'active');`;
});
for (const product of [
  {id:'deepsea-duo',name:'深海雙卡組合',cardIds:['25','13']},
  {id:'wildland-duo',name:'荒野雙卡組合',cardIds:['08','11']},
  {id:'inferno-duo',name:'烈焰雙卡組合',cardIds:['29','18']}
]) rows.push(`INSERT OR IGNORE INTO catalog_products(id,data,status) VALUES (${quote(product.id)},${quote(JSON.stringify({...product,coinPrice:30}))},'active');`);
fs.writeFileSync(path.join(root,'migrations/0005_seed_catalog.sql'),'-- Generated by node scripts/build-catalog-seed.cjs; does not overwrite existing catalog edits.\n'+rows.join('\n')+'\n');
