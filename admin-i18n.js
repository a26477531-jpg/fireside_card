let language = 'zh-TW';
try {
  const saved = localStorage.getItem('fireside-admin-language') || localStorage.getItem('fireside-language');
  if (saved === 'en') language = 'en';
} catch {}
export const getLanguage = () => language;
// Use the same collection names as the public card library.
const englishCollections = {'深海軍團':'Deepsea Legion','荒野之盟':'Wildland Alliance','暗影領域':'Shadow Realm'};
export function cardName(card) {
  if (!card) return '';
  if ((card.sourceLanguage || 'zh-TW') === language) return card.name;
  return card.translations?.[language]?.name?.trim() || card.name;
}
export function collectionName(value) {
  return language === 'en' ? englishCollections[value] || value : value;
}
// Match the saved name, not the product ID, so renamed products and order snapshots stay accurate.
const englishBundles = {
  '深海雙卡組合':'Deepsea Duo Pack',
  '荒野雙卡組合':'Wildland Duo Pack',
  '烈焰雙卡組合':'Inferno Duo Pack'
};
export function bundleName(product, locale = language) {
  const name=typeof product==='string'?product:product.name;
  if(typeof product==='object') {
    if(product.sourceLanguage===locale)return name;
    const translated=product.translations?.[locale]?.name?.trim();
    if(translated)return translated;
  }
  return locale === 'en' ? englishBundles[name] || name : name;
}
const messages = new Map();
export function t(key, values = {}) {
  const result = (language === 'en' ? english[key] ?? key : key).replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
  messages.set(result, {key, values});
  return result;
}
export function applyLanguage() {
  document.documentElement.lang = language === 'en' ? 'en' : 'zh-Hant';
  document.title = t('管理後台｜爐邊卡牌');
  document.querySelectorAll('[data-i18n]').forEach(el => el.textContent = t(el.dataset.i18n));
  for (const attribute of ['placeholder', 'aria-label']) {
    document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(el => el.setAttribute(attribute, t(el.getAttribute(`data-i18n-${attribute}`))));
  }
}
export function setLanguage(value) {
  language = value === 'en' ? 'en' : 'zh-TW';
  try { localStorage.setItem('fireside-admin-language', language); } catch {}
  // Only interface messages are updated; never walk or translate catalog/user data.
  for (const id of ['access','notice','form-error','order-summary','translation-status','editor-title','save']) {
    const el = document.getElementById(id), message = messages.get(el.textContent);
    if (message && !el.children.length) el.textContent = t(message.key, message.values);
  }
  applyLanguage();
}
